<h1 class="pagina-titel">⚖️ Patiëntenrechten</h1>
<p class="pagina-subtitel">De rechten die je hebt. Op papier althans. In de praktijk? Tja...</p>

<div class="rechten-intro">
    <h3 style="color: var(--accent); font-family: 'Permanent Marker', cursive; margin-bottom: 0.5rem;">
        Wet betreffende de rechten van de patiënt
    </h3>
    <p style="line-height: 1.7;">
        <strong>Wet van 22 augustus 2002</strong> — Belgisch Staatsblad 26 september 2002.<br>
        Deze wet beschermt jouw rechten als patiënt in België. Ja, ook als psychiatrisch patiënt.
        Ja, ook in een gesloten afdeling. Ja, ook als ze zeggen dat het "voor je eigen bestwil" is.
    </p>
    <p style="margin-top: 1rem; color: var(--accent2); font-weight: 700;">
        💡 Ken je rechten. Want niemand anders gaat ze voor je opzoeken.
    </p>
</div>

<div class="rechten-artikel">
    <h3>Artikel 5 — Recht op kwaliteitsvolle dienstverstrekking</h3>
    <p>
        Elke patiënt heeft recht op kwaliteitsvolle dienstverstrekking die beantwoordt aan zijn behoeften.
        Dit met eerbiediging van de menselijke waardigheid en de zelfbeschikking, zonder enig onderscheid
        op welke grond ook.
    </p>
</div>

<div class="rechten-artikel">
    <h3>Artikel 6 — Recht op vrije keuze van beroepsbeoefenaar</h3>
    <p>
        De patiënt heeft het recht de beroepsbeoefenaar vrij te kiezen en deze keuze te wijzigen,
        behoudens beperkingen opgelegd krachtens de wet.
    </p>
</div>

<div class="rechten-artikel">
    <h3>Artikel 7 — Recht op informatie over de gezondheidstoestand</h3>
    <p>
        De patiënt heeft recht op alle hem betreffende informatie die nodig is om inzicht te krijgen
        in zijn gezondheidstoestand en de vermoedelijke evolutie ervan. De informatie wordt verstrekt
        in een duidelijke taal.
    </p>
    <p style="margin-top: 0.5rem; color: var(--accent2); font-size: 0.9rem;">
        ⚡ Vertaling: ze MOETEN je uitleggen wat er aan de hand is, in woorden die je begrijpt.
        "Het is complex" is geen antwoord.
    </p>
</div>

<div class="rechten-artikel">
    <h3>Artikel 8 — Recht op toestemming (informed consent)</h3>
    <p>
        De patiënt heeft het recht om geïnformeerd, voorafgaandelijk en vrij toe te stemmen in iedere
        tussenkomst van de beroepsbeoefenaar. De toestemming wordt uitdrukkelijk gegeven, behalve
        wanneer de beroepsbeoefenaar, na de patiënt voldoende te hebben geïnformeerd, uit de
        gedragingen van de patiënt redelijkerwijs diens toestemming kan afleiden.
    </p>
    <p style="margin-top: 0.5rem; color: var(--accent2); font-size: 0.9rem;">
        ⚡ Je hebt het recht om NEEN te zeggen tegen een behandeling. Ja, ook medicatie.
    </p>
</div>

<div class="rechten-artikel">
    <h3>Artikel 9 — Recht op een zorgvuldig bijgehouden patiëntendossier</h3>
    <p>
        De patiënt heeft recht op een zorgvuldig bijgehouden en veilig bewaard patiëntendossier.
        De patiënt heeft het recht op inzage in het hem betreffende patiëntendossier.
        Het recht op afschrift van het geheel of een gedeelte van het patiëntendossier wordt
        uitgeoefend tegen kostprijs.
    </p>
    <p style="margin-top: 0.5rem; color: var(--accent2); font-size: 0.9rem;">
        ⚡ Je mag je eigen dossier inkijken. Ze MOETEN je een kopie geven als je erom vraagt.
    </p>
</div>

<div class="rechten-artikel">
    <h3>Artikel 10 — Recht op bescherming van de persoonlijke levenssfeer</h3>
    <p>
        De patiënt heeft recht op bescherming van zijn persoonlijke levenssfeer bij iedere
        tussenkomst van de beroepsbeoefenaar. Geen enkele inmenging is toegestaan tenzij de
        patiënt daarmee instemt.
    </p>
</div>

<div class="rechten-artikel">
    <h3>Artikel 11 — Recht op klachtenbemiddeling</h3>
    <p>
        De patiënt heeft het recht een klacht neer te leggen bij de bevoegde ombudsfunctie in
        verband met de uitoefening van zijn rechten. De ombudsfunctie heeft als opdracht het
        voorkomen van klachten door het bevorderen van de communicatie tussen de patiënt en
        de beroepsbeoefenaar, en het bemiddelen bij klachten.
    </p>
    <p style="margin-top: 0.5rem; color: var(--accent2); font-size: 0.9rem;">
        ⚡ Er MOET een ombudsdienst zijn in elk ziekenhuis. Vraag ernaar.
    </p>
</div>

<div class="rechten-artikel">
    <h3>Artikel 14 — Vertegenwoordiging van de patiënt</h3>
    <p>
        De rechten, zoals vastgesteld door deze wet, worden door een door de patiënt aangewezen
        vertegenwoordiger uitgeoefend indien de patiënt niet in staat is de rechten zelf uit te oefenen.
        De vertegenwoordiger dient bij de uitoefening van de rechten van de patiënt zo veel mogelijk
        de patiënt zelf te betrekken, in verhouding tot diens begripsvermogen.
    </p>
</div>

